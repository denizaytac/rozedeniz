// Current language
let currentLang = 'de';

// Initialize
document.addEventListener('DOMContentLoaded', function() {
    // Set up language switcher
    const langButtons = document.querySelectorAll('.lang-btn');

    langButtons.forEach(btn => {
        btn.addEventListener('click', function() {
            const lang = this.getAttribute('data-lang');
            switchLanguage(lang);

            // Update active state
            langButtons.forEach(b => b.classList.remove('active'));
            this.classList.add('active');
        });
    });

    // Load saved language or default
    const savedLang = localStorage.getItem('preferredLanguage') || 'de';
    switchLanguage(savedLang);

    // Update active button
    document.querySelector(`[data-lang="${savedLang}"]`).classList.add('active');
    document.querySelectorAll('.lang-btn').forEach(btn => {
        if (btn.getAttribute('data-lang') !== savedLang) {
            btn.classList.remove('active');
        }
    });

    // Set up FAQ accordion
    initializeFAQAccordion();
});

// Switch language function
function switchLanguage(lang) {
    currentLang = lang;
    localStorage.setItem('preferredLanguage', lang);

    // Update all translatable elements
    const elements = document.querySelectorAll('[data-i18n]');

    elements.forEach(element => {
        const key = element.getAttribute('data-i18n');
        const translation = translations[lang][key];

        if (translation) {
            // Check if it contains HTML
            if (translation.includes('<')) {
                element.innerHTML = translation;
            } else {
                element.textContent = translation;
            }
        }
    });

    // Update HTML lang attribute
    document.documentElement.lang = lang;
}

// FAQ Accordion functionality
function initializeFAQAccordion() {
    const faqQuestions = document.querySelectorAll('.faq-question');

    faqQuestions.forEach(question => {
        question.addEventListener('click', function() {
            const faqItem = this.parentElement;
            const isActive = faqItem.classList.contains('active');

            // Toggle the clicked item
            faqItem.classList.toggle('active');

            // Update icon
            const icon = this.querySelector('.faq-icon');
            if (icon) {
                icon.textContent = isActive ? '+' : '−';
            }
        });
    });
}

// Parallax Effect for Hero Background
function initParallax() {
    const heroBackground = document.querySelector('.hero-background');
    const hero = document.querySelector('.hero');

    if (!heroBackground || !hero) return;

    let ticking = false;

    function updateParallax() {
        const scrolled = window.pageYOffset;
        const heroHeight = hero.offsetHeight;

        // Only apply parallax while hero is visible
        if (scrolled < heroHeight) {
            // Move background slower than scroll (0.5 = half speed)
            const yPos = scrolled * 0.5;
            heroBackground.style.transform = `translateY(${yPos}px) scale(1.01)`;
        }

        ticking = false;
    }

    function requestTick() {
        if (!ticking) {
            window.requestAnimationFrame(updateParallax);
            ticking = true;
        }
    }

    window.addEventListener('scroll', requestTick, { passive: true });

    // Initial call
    updateParallax();
}

// Initialize parallax on page load
document.addEventListener('DOMContentLoaded', function() {
    initParallax();
});

// Smooth scroll for any future navigation links
document.querySelectorAll('a[href^="#"]').forEach(anchor => {
    anchor.addEventListener('click', function (e) {
        e.preventDefault();
        const target = document.querySelector(this.getAttribute('href'));
        if (target) {
            target.scrollIntoView({
                behavior: 'smooth',
                block: 'start'
            });
        }
    });
});
